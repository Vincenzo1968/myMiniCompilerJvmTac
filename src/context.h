#ifndef CONTEXT_H
#define CONTEXT_H

#include <stdio.h>
#include "symtab.h"
#include "scanner.h"
#include "ast.h"
#include <stdint.h>

#ifndef JVM_MAX_CP_BYTES
#define JVM_MAX_CP_BYTES 65536
#endif

#ifndef JVM_MAX_CODE_BYTES
#define JVM_MAX_CODE_BYTES 65536
#endif

/* Simple pool for real constants (float/double) requiring a memory address */
typedef struct {
    char *label;
    double value;
} RealConst;

typedef struct {
    int blockId;          /* -1 = global scope, >= 0 = block id */
    char *name;
    enumTipo0 t0;
    enumTipo1 t1;
    enumTipo2 t2;
    Valore val;
    char bInizializzato;
} InterpVarDecl;

/* Functions (prototypes and definitions) */
typedef struct {
	char *name; 
	char *uniqueName; /* unique name within the entire program (used by TAC and backend) */
	enumTipo0 t0;     /* T_SIMPLE or T_ARRAY (always by reference) */
	enumTipo1 t1; 
	int isRef;        /* scalar parameter passed by reference ('ref') */
	int dims;         /* number of dimensions if an array */
} FuncParam;

typedef struct {
    char *name;
    int isVoid;
    enumTipo1 retType;  /* meaningful only if !isVoid */
    int nparams;
    FuncParam *params;
    int defined;        /* 1 after definition (body) */
    int line;
    nodeType *body;     /* Body T_CODE_BLOCK (NULL until defined) */
} FuncDef;

typedef struct {
    InterpVarDecl *decls;
    int count;
    int cap;
    int nextBlockId;
    int currentBlockId;
    int rootInitDone;
    int nextRuntimeBlock;
} InterpDeclTable;

typedef struct CompilerContext {
    Scope g_Scope;
    Scope interpScope;
    InterpDeclTable interpDecls;
    enumTipo1 g_t1;
    int g_label;
    int g_temp;
    
    uint16_t g_ConstantPoolCount;
    uint8_t g_ArrayConstantPool[JVM_MAX_CP_BYTES];
    uint8_t g_ArrayCode[JVM_MAX_CODE_BYTES];
    int g_IndexConstantPool;
    int g_IndexBytecodeArray;
    int g_myType1;
    uint16_t g_max_stack;
    uint16_t g_max_locals;
    uint32_t g_code_length;
    int g_cur_stack;

    Token g_Token;
    int g_isCodeBlock;
    int g_isStmtList;
    int g_isREAD;
    int g_numErrors;
    int g_numWarnings;
    int g_currType;
    Valore g_currConstValue;
    int g_currConstType;
    //nodeType *g_stack;
    nodeType *g_stack[4096];
    int g_top;
    int g_genTAC;
    int g_genJVM;
    int g_NextFrameIndex;
    /* Assignments generated by declaration initializers
    ("int x = 8;"): these are collected during `decl_list` and subsequently prepended
    to the `stmt_list` of the block that contains them. */
    nodeType **g_initNodes;
    int g_initCount;
    int g_initCap;

    /* functions */
    FuncDef *funcs;
    int funcCount;
    int funcCap;
    int g_curFunc;          /* index of the function currently being parsed, -1 in the main program */
    /* interpreter: state of the active 'return' */
    int interpReturning;
    Valore interpRetVal;
    enumTipo1 interpRetType;

    char *g_szInput;
    int g_pos;
    int g_line;
    int g_column;
    int g_depth;

    RealConst *real_consts;
    int real_const_count;
} CompilerContext;

void ctx_init(CompilerContext *ctx);
void ctx_interp_cleanup(CompilerContext *ctx);

/* Function table. funcFind: index or -1. funcDeclare: adds (takes ownership
   di params) and returns the index. funcSignatureEquals: same return type and same parameters. */
int funcFind(CompilerContext *ctx, const char *name);
int funcDeclare(CompilerContext *ctx, const char *name, int isVoid, enumTipo1 retType, int nparams, FuncParam *params, int line);
int funcSignatureEquals(const FuncDef *a, int isVoid, enumTipo1 retType, int nparams, const FuncParam *params);
void funcFreeParams(FuncParam *params, int nparams);

#endif /* CONTEXT_H */
